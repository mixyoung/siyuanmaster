// Generates src/generated/wiki-templates.ts from catalog/wiki-templates.json.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, "..");
export const wikiTemplateCatalogPath = path.join(
  rootDir,
  "catalog",
  "wiki-templates.json",
);
export const wikiTemplateOutPath = path.join(
  rootDir,
  "src",
  "generated",
  "wiki-templates.ts",
);

export function renderWikiTemplateModule(catalog) {
  return [
    "// AUTO-GENERATED by scripts/generate-wiki-templates.mjs — do not edit by hand.",
    "// Source of truth: catalog/wiki-templates.json",
    "// Regenerate with: pnpm run generate",
    "",
    `export const WIKI_TEMPLATE_CATALOG = ${JSON.stringify(catalog)} as const;`,
    "",
  ].join("\n");
}

async function main() {
  const catalog = JSON.parse(
    await readFile(wikiTemplateCatalogPath, "utf8"),
  );
  await writeFile(
    wikiTemplateOutPath,
    renderWikiTemplateModule(catalog),
    "utf8",
  );
  console.log(`Generated ${path.relative(rootDir, wikiTemplateOutPath)}`);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await main();
}
